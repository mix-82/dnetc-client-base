/* ---- kernel interface --------------------------------------------------- */

/* A kernel checks nbatch batches of keys. Key number idx (0, 1, 2, ...) uses
   t = hi0 + idx, L2 = t & 0xff, L1 = l1 + (t >> 8), L0 = l0, and its two
   encrypted words go to out_a[idx] and out_b[idx]. */
typedef struct
{
  uint32_t l0, l1, hi0, nbatch;
  uint32_t plain_lo, plain_hi, pad0, pad1;
  uint32_t *out_a, *out_b;
  uint32_t *scratch;         /* 26 * streams vectors, for the SVE kernels */
  const uint32_t *consts;    /* P + i*Q, i = 0..25 */
} kargs_t;

_Static_assert(offsetof(kargs_t, hi0) == 8 && offsetof(kargs_t, plain_lo) == 16 &&
               offsetof(kargs_t, out_a) == 32 && offsetof(kargs_t, scratch) == 48 &&
               offsetof(kargs_t, consts) == 56, "kargs_t layout (see gen_kernels.py)");

static uint32_t ks_consts[26];

