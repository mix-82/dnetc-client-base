/* ---- variants -------------------------------------------------------------- */

enum { KIND_C, KIND_SME, KIND_SVE };   /* C function; SVE kernel under smstart; SVE kernel as is */

typedef struct
{
  char name[32];
  int kind;
  void (*fn)(void);
  uint32_t keys_per_batch;
  uint32_t code_size;     /* SVE kernels: for locating a fault */
  int ok;                 /* passed the check */
  double rate;            /* keys per second, one thread */
} variant_t;

#define MAX_VARIANTS 32
static variant_t variants[MAX_VARIANTS];
static int nvariants;

static void add_variant(const char *name, int kind, void (*fn)(void), uint32_t keys_per_batch,
                        uint32_t code_size)
{
  variant_t *v = &variants[nvariants++];
  snprintf(v->name, sizeof(v->name), "%s", name);
  v->kind = kind;
  v->fn = fn;
  v->keys_per_batch = keys_per_batch;
  v->code_size = code_size;
  v->ok = 0;
  v->rate = 0;
}

static void run_kernel(const variant_t *v, kargs_t *a)
{
  if (v->kind == KIND_C)
    ((void (*)(const kargs_t *))v->fn)(a);
  else if (v->kind == KIND_SME)
    (stub_sm)(v->fn, a);
  else
    (stub_plain)(v->fn, a);
}

/* ---- catching illegal instructions ------------------------------------------ */

static sigjmp_buf guard_jb;
static volatile sig_atomic_t guard_on;
static volatile uintptr_t fault_pc;
static volatile int fault_sig;
static int have_sme;      /* smstart / smstop work */

static void fault_handler(int sig, siginfo_t *si, void *ucv)
{
  ucontext_t *uc = (ucontext_t *)ucv;
  (void)si;
#if defined(__APPLE__)
  fault_pc = (uintptr_t)__darwin_arm_thread_state64_get_pc(uc->uc_mcontext->__ss);
#else
  fault_pc = (uintptr_t)uc->uc_mcontext.pc;
#endif
  fault_sig = sig;
  if (guard_on)
    siglongjmp(guard_jb, 1);
  _exit(3);
}

static void install_handlers(void)
{
  struct sigaction sa;
  memset(&sa, 0, sizeof(sa));
  sa.sa_sigaction = fault_handler;
  sa.sa_flags = SA_SIGINFO;
  sigemptyset(&sa.sa_mask);
  sigaction(SIGILL, &sa, NULL);
  sigaction(SIGBUS, &sa, NULL);
  sigaction(SIGSEGV, &sa, NULL);
}

/* Calls fn through a stub. Returns 0 and sets *ret, or -1 if it faulted. */
static int guarded_call(stub_t stub, void (*fn)(void), void *arg, uint64_t *ret)
{
  if (sigsetjmp(guard_jb, 1) == 0)
  {
    uint64_t r;
    guard_on = 1;
    r = stub(fn, arg);
    guard_on = 0;
    if (ret)
      *ret = r;
    return 0;
  }
  guard_on = 0;
  if (have_sme)
    do_smstop();   /* the fault may have been in streaming mode */
  return -1;
}

static void describe_fault(void (*fn)(void), uint32_t size)
{
  uintptr_t start = (uintptr_t)fn, pc = fault_pc;
  const char *sig = fault_sig == SIGILL ? "illegal instruction" :
                    fault_sig == SIGBUS ? "bus error" : "segmentation fault";
  if (pc >= start && pc < start + size)
    printf("%s at code offset 0x%lx (instruction word 0x%08x)", sig,
           (unsigned long)(pc - start), *(const uint32_t *)pc);
  else if (pc >= (uintptr_t)call_sm && pc < (uintptr_t)call_sm + call_sm_size)
    printf("%s in the smstart/smstop stub at offset 0x%lx (instruction word 0x%08x)", sig,
           (unsigned long)(pc - (uintptr_t)call_sm), *(const uint32_t *)pc);
  else
    printf("%s at pc %p", sig, (void *)pc);
}

