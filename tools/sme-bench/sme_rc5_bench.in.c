typedef uint64_t (*stub_t)(void (*fn)(void), void *arg);

/* call_sm and call_plain, set in main() through volatile pointers so that no
   compiler sees a call through a cast of the blob's declaration */
static stub_t stub_sm, stub_plain;

/* ---- plain C reference --------------------------------------------------- */

static inline uint32_t rotl32(uint32_t x, uint32_t s)
{
  s &= 31;
  return (x << s) | (x >> ((32 - s) & 31));
}

static void rc5_72_ref(uint32_t l0, uint32_t l1, uint32_t l2, uint32_t plain_lo, uint32_t plain_hi,
                       uint32_t *out_a, uint32_t *out_b)
{
  uint32_t S[26], L[3], A = 0, B = 0;
  int i, k;

  L[0] = l0; L[1] = l1; L[2] = l2;
  for (i = 0; i < 26; i++)
    S[i] = P + (uint32_t)i * Q;
  for (k = 0; k < 78; k++)
  {
    A = S[k % 26] = rotl32(S[k % 26] + A + B, 3);
    B = L[k % 3] = rotl32(L[k % 3] + A + B, A + B);
  }
  A = plain_lo + S[0];
  B = plain_hi + S[1];
  for (i = 1; i <= 12; i++)
  {
    A = rotl32(A ^ B, B) + S[2 * i];
    B = rotl32(B ^ A, A) + S[2 * i + 1];
  }
  *out_a = A;
  *out_b = B;
}

static void k_scalar(const kargs_t *a)
{
  uint32_t idx;
  for (idx = 0; idx < a->nbatch; idx++)
  {
    uint32_t t = a->hi0 + idx;
    rc5_72_ref(a->l0, a->l1 + (t >> 8), t & 0xff, a->plain_lo, a->plain_hi,
               &a->out_a[idx], &a->out_b[idx]);
  }
}

/* ---- NEON kernels (C intrinsics; W streams of 4 keys) -------------------- */

#if defined(__clang__)
#define UNROLL _Pragma("clang loop unroll(full)")
#elif defined(__GNUC__)
#define UNROLL _Pragma("GCC unroll 8")
#else
#define UNROLL
#endif

static inline uint32x4_t neon_rotl3(uint32x4_t t)
{
  return vsriq_n_u32(vshlq_n_u32(t, 3), t, 29);
}

static inline uint32x4_t neon_rotlv(uint32x4_t x, uint32x4_t s)
{
  int32x4_t left = vreinterpretq_s32_u32(vandq_u32(s, vdupq_n_u32(31)));
  int32x4_t right = vsubq_s32(left, vdupq_n_s32(32));   /* negative: shifts right */
  return vorrq_u32(vshlq_u32(x, left), vshlq_u32(x, right));
}

#define NEON_STEP(k, i, j, jp) \
  UNROLL for (w = 0; w < NW; w++) \
  { \
    uint32x4_t t = (k) < 26 ? vdupq_n_u32(P + (uint32_t)(i) * Q) : S[i][w]; \
    uint32x4_t s; \
    t = vaddq_u32(t, A[w]); \
    if (k) t = vaddq_u32(t, L[jp][w]); \
    A[w] = neon_rotl3(t); \
    S[i][w] = A[w]; \
    s = (k) ? vaddq_u32(A[w], L[jp][w]) : A[w]; \
    L[j][w] = neon_rotlv(vaddq_u32(L[j][w], s), s); \
  }

#define NEON_KERNEL(NAME, NWIDTH) \
static void NAME(const kargs_t *a) \
{ \
  enum { NW = NWIDTH }; \
  static const uint32_t lane_no[4] = { 0, 1, 2, 3 }; \
  const uint32x4_t lanes = vld1q_u32(lane_no); \
  uint32x4_t S[26][NW], A[NW], L[3][NW], eA[NW], eB[NW]; \
  uint32_t base = a->hi0, b, *oa = a->out_a, *ob = a->out_b; \
  int w, r; \
  for (b = 0; b < a->nbatch; b++) \
  { \
    UNROLL for (w = 0; w < NW; w++) \
    { \
      uint32x4_t t = vaddq_u32(vdupq_n_u32(base + 4u * (uint32_t)w), lanes); \
      L[2][w] = vandq_u32(t, vdupq_n_u32(0xff)); \
      L[1][w] = vaddq_u32(vdupq_n_u32(a->l1), vshrq_n_u32(t, 8)); \
      L[0][w] = vdupq_n_u32(a->l0); \
      A[w] = vdupq_n_u32(0); \
    } \
    base += 4u * NW; \
    KS_STEPS(NEON_STEP) \
    UNROLL for (w = 0; w < NW; w++) \
    { \
      eA[w] = vaddq_u32(vdupq_n_u32(a->plain_lo), S[0][w]); \
      eB[w] = vaddq_u32(vdupq_n_u32(a->plain_hi), S[1][w]); \
    } \
    for (r = 1; r <= 12; r++) \
    { \
      UNROLL for (w = 0; w < NW; w++) \
        eA[w] = vaddq_u32(neon_rotlv(veorq_u32(eA[w], eB[w]), eB[w]), S[2 * r][w]); \
      UNROLL for (w = 0; w < NW; w++) \
        eB[w] = vaddq_u32(neon_rotlv(veorq_u32(eB[w], eA[w]), eA[w]), S[2 * r + 1][w]); \
    } \
    UNROLL for (w = 0; w < NW; w++) \
    { \
      vst1q_u32(oa, eA[w]); oa += 4; \
      vst1q_u32(ob, eB[w]); ob += 4; \
    } \
  } \
}

