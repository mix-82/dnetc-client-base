/* distributed.net RC5-72 test cases (common/selftest.cpp):
   key hi, mid, lo, iv lo, hi, plain lo, hi, cypher lo, hi */
static const uint32_t dnet_cases[3][9] = {
  {0x000000C9,0x0C0353C0,0xD4E1FE85,0x1F59CE07,0x419A1486,0x20656854,0x6E6B6E75,0x562D285A,0x2FB7852A},
  {0x000000DE,0xEE0C6279,0xBF66F898,0x8F0FC4D4,0x5C7BE413,0x1850EA58,0x0E02AEE8,0x9D745D16,0xB796FAAB},
  {0x000000C6,0xE9386A44,0xC0F9D107,0x580D9BFA,0x545B2D79,0xDAB8806E,0xBAC12504,0x11D572B7,0x5DA4EDC8},
};

static int reference_selftest(void)
{
  int i, bad = 0;
  for (i = 0; i < 3; i++)
  {
    const uint32_t *c = dnet_cases[i];
    uint32_t a, b, l0, l1, l2;
    /* the client's key format switch (__SwitchRC572Format in common/problem.cpp) */
    l0 = (c[0] & 0x000000FFu) | ((c[1] >> 16) & 0x0000FF00u) | (c[1] & 0x00FF0000u) | ((c[1] << 16) & 0xFF000000u);
    l1 = (c[1] & 0x000000FFu) | ((c[2] >> 16) & 0x0000FF00u) | (c[2] & 0x00FF0000u) | ((c[2] << 16) & 0xFF000000u);
    l2 = c[2] & 0x000000FFu;
    rc5_72_ref(l0, l1, l2, c[5] ^ c[3], c[6] ^ c[4], &a, &b);
    if (a != c[7] || b != c[8])
      bad++;
  }
  return bad;
}

#define CHECK_KEYS 768u
#define MAX_KEYS_PER_BATCH 256u      /* 4 streams at a 2048-bit vector */
#define BUF_KEYS 8192u

typedef struct
{
  uint32_t *out_a, *out_b, *scratch;
} bufs_t;

static void *xalloc(size_t n)
{
  void *p = NULL;
  if (posix_memalign(&p, 256, n) != 0 || !p)
  {
    printf("out of memory\n");
    exit(2);
  }
  memset(p, 0, n);
  return p;
}

static void bufs_alloc(bufs_t *b)
{
  b->out_a = (uint32_t *)xalloc(BUF_KEYS * 4);
  b->out_b = (uint32_t *)xalloc(BUF_KEYS * 4);
  b->scratch = (uint32_t *)xalloc(26 * 4 * 256 + 256);
}

static void kargs_init(kargs_t *a, const bufs_t *b)
{
  memset(a, 0, sizeof(*a));
  a->l0 = 0x9E3C0F51u;
  a->l1 = 0xFFFFFFFEu;       /* the checks cross a carry into L1 and a wrap of L1 */
  a->hi0 = 0xF3u;
  a->plain_lo = 0x3F3CA662u;
  a->plain_hi = 0x2D0E0A7Bu;
  a->out_a = b->out_a;
  a->out_b = b->out_b;
  a->scratch = b->scratch;
  a->consts = ks_consts;
}

/* Returns the number of wrong keys, or -1 if the kernel faulted. */
static int check_variant(variant_t *v, const bufs_t *b)
{
  kargs_t a;
  uint32_t n, idx;
  int bad = 0;

  kargs_init(&a, b);
  a.nbatch = (CHECK_KEYS + v->keys_per_batch - 1) / v->keys_per_batch;
  n = a.nbatch * v->keys_per_batch;
  memset(b->out_a, 0x55, n * 4);
  memset(b->out_b, 0x55, n * 4);
  if (v->kind == KIND_C)
    run_kernel(v, &a);
  else if (guarded_call(v->kind == KIND_SME ? stub_sm : stub_plain, v->fn, &a, NULL) != 0)
    return -1;
  for (idx = 0; idx < n; idx++)
  {
    uint32_t t = a.hi0 + idx, ra, rb;
    rc5_72_ref(a.l0, a.l1 + (t >> 8), t & 0xff, a.plain_lo, a.plain_hi, &ra, &rb);
    if (b->out_a[idx] != ra || b->out_b[idx] != rb)
      bad++;
  }
  return bad;
}

/* ---- timing ------------------------------------------------------------------------ */

typedef struct
{
  const variant_t *v;
  double seconds;
  volatile int *go;
  double rate;
  int bad;
} job_t;

static void time_variant(job_t *job, const bufs_t *b)
{
  const variant_t *v = job->v;
  kargs_t a;
  uint64_t keys = 0;
  uint32_t chunk_batches = 2048u / v->keys_per_batch, n, idx;
  double t0, t1;

  if (chunk_batches < 1)
    chunk_batches = 1;
  kargs_init(&a, b);
  a.nbatch = chunk_batches;
  n = chunk_batches * v->keys_per_batch;
  run_kernel(v, &a);                 /* warm up */
  t0 = now_sec();
  do
  {
    int rep;
    for (rep = 0; rep < 8; rep++)
    {
      a.hi0 += n;
      run_kernel(v, &a);
      keys += n;
    }
    t1 = now_sec();
  } while (t1 - t0 < job->seconds);
  job->rate = (double)keys / (t1 - t0);
  /* the last chunk must still be right */
  job->bad = 0;
  for (idx = 0; idx < n; idx += 37)
  {
    uint32_t t = a.hi0 + idx, ra, rb;
    rc5_72_ref(a.l0, a.l1 + (t >> 8), t & 0xff, a.plain_lo, a.plain_hi, &ra, &rb);
    if (b->out_a[idx] != ra || b->out_b[idx] != rb)
      job->bad++;
  }
}

static void *thread_main(void *arg)
{
  job_t *job = (job_t *)arg;
  bufs_t b;
#if defined(__APPLE__)
  pthread_set_qos_class_self_np(QOS_CLASS_USER_INTERACTIVE, 0);
#endif
  bufs_alloc(&b);
  while (!*job->go)
    ;
  time_variant(job, &b);
  return NULL;
}

#define MAX_THREADS 64

static double time_threads(const variant_t *v, int nthreads, double seconds, int *bad)
{
  static job_t jobs[MAX_THREADS];
  pthread_t th[MAX_THREADS];
  volatile int go = 0;
  double total = 0;
  int i;

  *bad = 0;
  for (i = 0; i < nthreads; i++)
  {
    jobs[i].v = v;
    jobs[i].seconds = seconds;
    jobs[i].go = &go;
    if (pthread_create(&th[i], NULL, thread_main, &jobs[i]) != 0)
    {
      printf("cannot start thread %d\n", i);
      exit(2);
    }
  }
  usleep(20000);
  go = 1;
  for (i = 0; i < nthreads; i++)
  {
    pthread_join(th[i], NULL);
    total += jobs[i].rate;
    *bad += jobs[i].bad;
  }
  return total;
}

