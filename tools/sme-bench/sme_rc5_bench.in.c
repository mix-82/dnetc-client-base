/*
 * sme_rc5_bench: does Arm SME (streaming SVE) check RC5-72 keys faster than NEON?
 *
 * A probe, not part of the distributed.net client. It does no distributed.net
 * work: it encrypts with made-up keys and only measures speed.
 *
 * Build and run (macOS on Apple silicon, or Linux on arm64):
 *
 *     cc -O2 -o sme_rc5_bench sme_rc5_bench.c -lpthread
 *     ./sme_rc5_bench
 *
 * It takes about 30 seconds. Optional argument: seconds per measurement
 * (default 1.0), for example "./sme_rc5_bench 0.2" for a quick run.
 * The word "force" as an argument checks the SVE kernels even when a probe
 * failed (for testing the fault reports).
 *
 * What it does, in order, printing as it goes:
 *   1. system information (which SME features the system reports);
 *   2. a self-check of the plain C RC5-72 against distributed.net test keys;
 *   3. probes: each kind of instruction the SME kernels need is tried once,
 *      and an illegal instruction is reported instead of crashing;
 *   4. every kernel is checked against the plain C version;
 *   5. every kernel that passed is timed on one thread;
 *   6. the best NEON and best SME kernels are timed on several threads.
 *
 * The SME / SVE kernels are machine code generated by gen_kernels.py (the
 * readable assembly is kernels.S) and embedded below as .long words, so no
 * assembler support for SME is needed to build this file.
 */

