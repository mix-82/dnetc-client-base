#!/usr/bin/env python3
# Generate an RC5-72 AVX-512F core with C pipes x 16 lanes (C = 1..4),
# using the algorithm of MIX ZMM (rc5-72/amd64/r72-avx512z.asm).
#
# Usage: python3 gen.py C > r72b_cC.asm
#
# For C = 2 the generated code is meant to be instruction-for-instruction
# the same as r72-avx512z.asm (only the symbol name differs); "make verify"
# checks that. Other values of C widen or narrow every per-pipe group:
# - S table stride per subkey is 64*C bytes, pipes interleaved
# - ROM round-1 constants are 16*C dwords each
# - per pipe: A, B_0, B_1, B_2 and scratch T; C/D reuse the dead B_0/B_2
#   registers in the same order as the original (B1_0, B1_2, B2_0, B2_2, ...)
# - cipher.lo masks are merged with kortestw (C=2), korw+kortestw (C=3) or
#   korw+korw+kortestw (C=4); 64-bit match masks in the rare path for C > 2
#
# Batch size is 16*C keys. C=4 (64 keys) needs MINIMUM_ITERATIONS 192 and
# L0hi aligned to 64 in the client. C=3 (48 keys) is for benchmarking only:
# 48 does not divide 256, so batches straddle the L0hi byte carry and test
# wrong keys there.
#
# Function: s32 r72b_cC(RC5_72UnitWork *work, u32 *iterations, void *memblk)

import sys

P = 0xB7E15163
Q = 0x9E3779B9
M = 0xFFFFFFFF


def gen(C):
    K = 16 * C
    St = 64 * C
    log2 = {1: 4, 2: 5, 4: 6}.get(C)
    name = "r72b_c%d" % C

    A = ["zmm%d" % (6 + c) for c in range(C)]
    B = [["zmm%d" % (6 + C + 3 * c + j) for j in range(3)] for c in range(C)]
    T = ["zmm%d" % c for c in range(C)]
    dead = []
    for c in range(C):
        dead += [B[c][0], B[c][2]]
    Cr = dead[:C]
    Dr = dead[C:]

    def m(base, d):
        if d == 0:
            return "[%s]" % base
        if d > 0:
            return "[%s+%d]" % (base, d)
        return "[%s-%d]" % (base, -d)

    def S(c, n):
        return "[work_S+%d]" % (n * St + 64 * c)

    o = []
    e = o.append

    e("; RC5-72 AVX-512F benchmark core, %d pipe(s) x 16 lanes = %d keys per batch" % (C, K))
    e("; Generated by gen.py from the MIX ZMM algorithm (r72-avx512z.asm).")
    e("")
    e("section .text")
    e("BITS 64")
    e("")
    e("[GLOBAL %s]" % name)
    e("")
    e("%define RESULT_NOTHING 1")
    e("%define RESULT_FOUND   2")
    e("")
    e("%assign work_size 0")
    e("")
    e("%macro defidef 2")
    e("    %define %1 rsp+%2")
    e("%endmacro")
    e("")
    e("%macro defwork 1-2 1")
    e("    defidef %1,work_size")
    e("    %assign work_size work_size+4*(%2)")
    e("%endmacro")
    e("")
    e("%assign work32_size 0")
    e("")
    e("%macro defidef32 2")
    e("    %define %1 rbp+%2")
    e("%endmacro")
    e("")
    e("%macro defwork32 1-2 1")
    e("    defidef32 %1,work32_size")
    e("    %assign work32_size work32_size+32*(%2)")
    e("%endmacro")
    e("")
    e("%ifdef _WINDOWS")
    for r in range(6, 16):
        e("defwork save_xmm%d,4" % r)
    e("defwork save_rsi,2")
    e("defwork save_rdi,2")
    e("%endif")
    for r in ("rbx", "rbp", "r12", "r13", "r14", "r15"):
        e("defwork save_%s,2" % r)
    e("")
    for v in ("work_pre_B_0", "work_pre_B_1", "work_pre_B_2", "work_pre_S1", "work_pre_S2"):
        e("defwork %s" % v)
    e("")
    e("%assign work_size work_size + 64")
    e("%assign work_offset work_size")
    e("")
    e("defwork32 work_S, (26*%d)    ; %d pipes * 64 bytes per subkey" % (2 * C, C))
    e("")
    e("%assign work_size work_size + work32_size")
    e("%assign work_size (work_size + 7) & 0FFFFFFF8h")
    e("%assign work_size work_size + (8 - work_size % 16)")
    e("")
    offs = ["plainhi", "plainlo", "cipherhi", "cipherlo", "L0hi", "L0mid", "L0lo",
            "CMCcount", "CMChi", "CMCmid", "CMClo"]
    for n, f in enumerate(offs):
        e("%%define RC5_72UnitWork_%s rdi+%d" % (f, 4 * n))
    e("")
    for v, d in (("work_pre_B_0", 20), ("work_pre_B_1", 16), ("work_pre_B_2", 12),
                 ("work_pre_S1", 8), ("work_pre_S2", 4)):
        e("%%undef  %s" % v)
        e("%%define %s rbp-%d" % (v, d))
    e("")
    e("%define L0hi    r13d")
    e("%define L0mid   r14d")
    e("%define L0lo    r15d")
    e("")
    e("align 16")
    e("%s:" % name)
    e("")
    e("    sub     rsp, work_size")
    e("")
    e("%ifdef _WINDOWS")
    for r in range(6, 16):
        e("    vmovdqa [save_xmm%d], xmm%d" % (r, r))
    e("    mov     [save_rsi], rsi")
    e("    mov     [save_rdi], rdi")
    e("    mov     rdi, rcx")
    e("    mov     rsi, rdx")
    e("%endif")
    for r in ("rbx", "rbp", "r12", "r13", "r14", "r15"):
        e("    mov     [save_%s], %s" % (r, r))
    e("")
    e("    lea     rbp, [rsp+work_offset]")
    e("    and     rbp, -64")
    e("")
    e("    mov     r10d, [rsi]")
    if log2:
        e("    shr     r10d, %d           ; batches of %d keys" % (log2, K))
    else:
        e("    mov     eax, r10d")
        e("    xor     edx, edx")
        e("    mov     r11d, %d" % K)
        e("    div     r11d")
        e("    mov     r10d, eax          ; batches of %d keys" % K)
    e("")
    e("    mov     L0hi, [RC5_72UnitWork_L0hi]")
    e("    mov     L0mid, [RC5_72UnitWork_L0mid]")
    e("    mov     L0lo, [RC5_72UnitWork_L0lo]")
    e("")
    e("    lea     r12, %s" % S(0, 1))
    e("")
    e(".key_setup_1_outer_loop:")
    e("    mov     ecx, L0lo")
    e("    add     ecx, 0xBF0A8B1D")
    e("    rol     ecx, 29")
    e("    mov     [work_pre_B_0], ecx")
    e("")
    e("    mov     eax, ecx")
    e("    add     eax, 0x15235639")
    e("    rol     eax, 3")
    e("    mov     [work_pre_S1], eax")
    e("    add     ecx, eax")
    e("")
    e(".key_setup_1_mid_loop:")
    e("    lea     edx, [L0mid+ecx]")
    e("    rol     edx, cl")
    e("    mov     [work_pre_B_1], edx")
    e("")
    e("    add     eax, edx")
    e("    add     eax, 0xF45044D5")
    e("    rol     eax, 3")
    e("    mov     [work_pre_S2], eax")
    e("    add     edx, eax")
    e("    mov     [work_pre_B_2], edx")
    e("")
    e("align 16")
    e(".key_setup_1_inner_loop:")
    e("    vpbroadcastd    %s, [work_pre_S2]" % A[0])
    e("    vpbroadcastd    %s, [work_pre_B_0]" % B[0][0])
    e("    vpbroadcastd    %s, [work_pre_B_1]" % B[0][1])
    for c in range(1, C):
        e("    vmovdqa32       %s, %s" % (A[c], A[0]))
    for c in range(1, C):
        e("    vmovdqa32       %s, %s" % (B[c][0], B[0][0]))
    for c in range(1, C):
        e("    vmovdqa32       %s, %s" % (B[c][1], B[0][1]))
    e("")
    e("    vpbroadcastd    %s, [work_pre_S1]" % T[0])
    for c in range(C):
        e("    vmovdqa32 %s, %s" % (S(c, 1), T[0]))
    for c in range(C):
        e("    vmovdqa32 %s, %s" % (S(c, 2), A[0]))
    e("")
    e("    vpbroadcastd    %s, [RC5_72UnitWork_L0hi]" % B[0][2])
    e("    vpbroadcastd    %s, [work_pre_B_2]" % T[0])
    for c in range(1, C):
        e("    vmovdqa32       %s, %s" % (B[c][2], B[0][2]))
    for c in range(1, C):
        e("    vmovdqa32       %s, %s" % (T[c], T[0]))
    e("")
    for c in range(C):
        e("    vpaddd  %s, %s, [rel .I%d]" % (B[c][2], B[c][2], c + 1))
        e("    vpaddd  %s, %s, %s" % (B[c][2], B[c][2], T[c]))
        e("    vprolvd %s, %s, %s" % (B[c][2], B[c][2], T[c]))
        e("")
    e("    lea     rax, [rel .IS3]")
    e("    lea     rdx, %s" % S(0, 3))
    e("    lea     r8, [work_S - %d]" % St)
    e("    xor     ebx, ebx")
    e("    jmp     .round1")
    e("")

    e("align 16")
    e(".round:")
    e("    ; step A: add S, add B_1, update B_2")
    e("    vpaddd  %s, %s, %s" % (A[0], A[0], m("rax", -St)))
    e("    cmp     ebx, 7")
    e("    cmove   rdx, r12")
    for c in range(1, C):
        e("    vpaddd  %s, %s, %s" % (A[c], A[c], m("rax", -St + 64 * c)))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (A[c], A[c], B[c][1]))
    e("    add     ebx, 1")
    for c in range(C):
        e("    vprold  %s, %s, 3" % (A[c], A[c]))
    for c in range(C):
        e("    vmovdqa32 %s, %s" % (m("rdx", -St + 64 * c), A[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (T[c], B[c][1], A[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (B[c][2], B[c][2], T[c]))
    for c in range(C):
        e("    vprolvd %s, %s, %s" % (B[c][2], B[c][2], T[c]))
    e("")
    e(".round1:")
    e("    ; step B: add S, add B_2, update B_0")
    e("    cmp     ebx, 8")
    e("    cmove   rax, rdx")
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (A[c], A[c], m("rax", 64 * c)))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (A[c], A[c], B[c][2]))
    for c in range(C):
        e("    vprold  %s, %s, 3" % (A[c], A[c]))
    for c in range(C):
        e("    vmovdqa32 %s, %s" % (m("rdx", 64 * c), A[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (T[c], B[c][2], A[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (B[c][0], B[c][0], T[c]))
    for c in range(C):
        e("    vprolvd %s, %s, %s" % (B[c][0], B[c][0], T[c]))
    e("")
    e("    ; step C: add S, add B_0, update B_1")
    e("    cmp     ebx, 16")
    e("    cmove   rdx, r8")
    e("    cmove   rax, r8")
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (A[c], A[c], m("rax", St + 64 * c)))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (A[c], A[c], B[c][0]))
    for c in range(C):
        e("    vprold  %s, %s, 3" % (A[c], A[c]))
    for c in range(C):
        e("    vmovdqa32 %s, %s" % (m("rdx", St + 64 * c), A[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (T[c], B[c][0], A[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (B[c][1], B[c][1], T[c]))
    for c in range(C):
        e("    vprolvd %s, %s, %s" % (B[c][1], B[c][1], T[c]))
    e("")
    e("    add     rax, %d" % (3 * St))
    e("    add     rdx, %d" % (3 * St))
    e("    cmp     ebx, 24")
    e("    jne     .round")
    e("")
    e(".encryptSetup:")
    e("    vpbroadcastd  zmm0, [RC5_72UnitWork_plainlo]")
    e("    vpbroadcastd  zmm1, [RC5_72UnitWork_plainhi]")
    for c in range(C):
        e("    vpaddd  %s, zmm0, %s" % (Cr[c], S(c, 0)))
        e("    vpaddd  %s, zmm1, %s" % (Dr[c], S(c, 1)))
    e("")
    e("    lea     rax, [work_S + %d]" % (2 * St))
    e("    xor     ebx, ebx")
    e("")
    e("align 16")
    e(".encrypt:")
    e("    inc     ebx")
    for c in range(C):
        e("    vpxord  %s, %s, %s" % (Cr[c], Cr[c], Dr[c]))
    for c in range(C):
        e("    vprolvd %s, %s, %s" % (Cr[c], Cr[c], Dr[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (Cr[c], Cr[c], m("rax", 64 * c)))
    for c in range(C):
        e("    vpxord  %s, %s, %s" % (Dr[c], Dr[c], Cr[c]))
    for c in range(C):
        e("    vprolvd %s, %s, %s" % (Dr[c], Dr[c], Cr[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (Dr[c], Dr[c], m("rax", St + 64 * c)))
    e("    add     rax, %d" % (2 * St))
    e("    cmp     ebx, 11")
    e("    jne     .encrypt")
    e("")
    e(".encryptEnd:")
    for c in range(C):
        e("    vpxord  %s, %s, %s" % (Cr[c], Cr[c], Dr[c]))
    for c in range(C):
        e("    vprolvd %s, %s, %s" % (Cr[c], Cr[c], Dr[c]))
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (Cr[c], Cr[c], S(c, 24)))
    e("")
    e(".checkKey:")
    for c in range(C):
        e("    vpcmpeqd    k%d, %s, [RC5_72UnitWork_cipherlo]{1to16}" % (c + 1, Cr[c]))
    if C == 1:
        e("    kortestw    k1, k1")
    elif C == 2:
        e("    kortestw    k1, k2")
    elif C == 3:
        e("    korw        k5, k1, k2")
        e("    kortestw    k5, k3")
    else:
        e("    korw        k5, k1, k2")
        e("    korw        k6, k3, k4")
        e("    kortestw    k5, k6")
    e("    jnz         .checkHi")
    e("")
    e(".nextKey:")
    e("    dec     r10d")
    e("    jz      .finished_Found_nothing")
    e("")
    e("    add     r13b, %d" % K)
    e("    movzx   L0hi, r13b")
    e("    mov     [RC5_72UnitWork_L0hi], L0hi")
    e("    jnc     .key_setup_1_inner_loop")
    e("")
    e("    bswap   L0mid")
    e("    adc     L0mid, 0")
    e("    bswap   L0mid")
    e("    mov     eax, [work_pre_S1]")
    e("    jnc     .key_setup_1_mid_loop")
    e("")
    e("    bswap   L0lo")
    e("    adc     L0lo, 0")
    e("    bswap   L0lo")
    e("    jmp     .key_setup_1_outer_loop")
    e("")
    e(".checkHi:")
    e("    ; rare path; must not touch ecx (the mid loop reuses it)")
    wide = C > 2
    e("    kmovw   eax, k1")
    if C >= 2:
        e("    kmovw   edx, k2")
        e("    shl     edx, 16")
        e("    or      eax, edx")
    for c in range(2, C):
        e("    kmovw   edx, k%d" % (c + 1))
        e("    shl     rdx, %d" % (16 * c))
        e("    or      rax, rdx")
    e("")
    for c in range(C):
        e("    vpaddd  %s, %s, %s" % (A[c], A[c], S(c, 25)))
        e("    vpaddd  %s, %s, %s" % (A[c], A[c], B[c][1]))
        e("    vprold  %s, %s, 3" % (A[c], A[c]))
        e("    vpxord  %s, %s, %s" % (Dr[c], Dr[c], Cr[c]))
        e("    vprolvd %s, %s, %s" % (Dr[c], Dr[c], Cr[c]))
        e("    vpaddd  %s, %s, %s" % (Dr[c], Dr[c], A[c]))
        e("    vpcmpeqd    k%d, %s, [RC5_72UnitWork_cipherhi]{1to16}" % (c + 1, Dr[c]))
    e("    kmovw   edx, k1")
    if C >= 2:
        e("    kmovw   r9d, k2")
        e("    shl     r9d, 16")
        e("    or      edx, r9d")
    for c in range(2, C):
        e("    kmovw   r9d, k%d" % (c + 1))
        e("    shl     r9, %d" % (16 * c))
        e("    or      rdx, r9")
    if wide:
        e("    and     rdx, rax")
    else:
        e("    and     edx, eax")
    e("    jnz     .saveFoundKey")
    e("")
    if wide:
        e("    popcnt  r11, rax")
        e("    add     dword [RC5_72UnitWork_CMCcount], r11d")
        e("    bsr     r9, rax")
    else:
        e("    popcnt  r11d, eax")
        e("    add     dword [RC5_72UnitWork_CMCcount], r11d")
        e("    bsr     r9d, eax")
    e("    add     r9d, L0hi")
    e("    mov     [RC5_72UnitWork_CMChi], r9d")
    e("    mov     [RC5_72UnitWork_CMCmid], L0mid")
    e("    mov     [RC5_72UnitWork_CMClo], L0lo")
    e("    jmp     .nextKey")
    e("")
    e(".saveFoundKey:")
    if wide:
        e("    bsf     r9, rdx")
        e("    mov     ecx, r9d")
        e("    mov     r11d, 2")
        e("    shl     r11, cl")
        e("    dec     r11")
        e("    and     rax, r11")
        e("    popcnt  r11, rax")
    else:
        e("    bsf     r9d, edx")
        e("    mov     ecx, r9d")
        e("    mov     r11d, 2")
        e("    shl     r11d, cl")
        e("    dec     r11d")
        e("    and     eax, r11d")
        e("    popcnt  r11d, eax")
    e("    add     dword [RC5_72UnitWork_CMCcount], r11d")
    e("    lea     r11d, [r9 + r13]")
    e("    mov     [RC5_72UnitWork_CMChi], r11d")
    e("    mov     [RC5_72UnitWork_CMCmid], L0mid")
    e("    mov     [RC5_72UnitWork_CMClo], L0lo")
    e("")
    e("    mov     eax, [rsi]")
    if log2:
        e("    shr     eax, %d" % log2)
        e("    sub     eax, r10d")
        e("    shl     eax, %d" % log2)
    else:
        e("    xor     edx, edx")
        e("    mov     r11d, %d" % K)
        e("    div     r11d")
        e("    sub     eax, r10d")
        e("    imul    eax, eax, %d" % K)
    e("    add     eax, r9d")
    e("    mov     [rsi], eax")
    e("")
    e("    mov     [RC5_72UnitWork_L0mid], L0mid")
    e("    mov     [RC5_72UnitWork_L0lo], L0lo")
    e("    mov     eax, RESULT_FOUND")
    e("    jmp     .finished")
    e("")
    e(".finished_Found_nothing:")
    e("    add     r13b, %d" % K)
    e("    movzx   L0hi, r13b")
    e("    mov     [RC5_72UnitWork_L0hi], L0hi")
    e("")
    e("    bswap   L0mid")
    e("    bswap   L0lo")
    e("    adc     L0mid, 0")
    e("    adc     L0lo, 0")
    e("    bswap   L0mid")
    e("    bswap   L0lo")
    e("    mov     [RC5_72UnitWork_L0mid], L0mid")
    e("    mov     [RC5_72UnitWork_L0lo], L0lo")
    e("    mov     eax, RESULT_NOTHING")
    e("")
    e(".finished:")
    e("")
    e("%ifdef _WINDOWS")
    for r in range(6, 16):
        e("    vmovdqa xmm%d, [save_xmm%d]" % (r, r))
    e("    mov     rsi, [save_rsi]")
    e("    mov     rdi, [save_rdi]")
    e("%endif")
    for r in ("rbx", "rbp", "r12", "r13", "r14", "r15"):
        e("    mov     %s, [save_%s]" % (r, r))
    e("")
    e("    add     rsp, work_size")
    e("")
    e("    vzeroupper")
    e("    ret")
    e("")
    e("%ifidn __OUTPUT_FORMAT__, win64")
    e("section .rdata align=64")
    e("%else")
    e("section .rodata align=64")
    e("%endif")
    e("align 64")
    for c in range(C):
        e(".I%d:    dd %s" % (c + 1, ", ".join("%2d" % (16 * c + n) for n in range(16))))
    for n in list(range(3, 26)) + [0]:
        if n == 0:
            v = 0xBF0A8B1D
        else:
            v = (P + n * Q) & M
        e(".IS%d:   times %d dd 0x%08X" % (n, 16 * C, v))
    e("")
    e("%ifidn __OUTPUT_FORMAT__, elf64")
    e("section .note.GNU-stack noalloc noexec nowrite progbits")
    e("%endif")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in ("1", "2", "3", "4"):
        sys.stderr.write("usage: gen.py C   (C = 1..4)\n")
        sys.exit(1)
    sys.stdout.write(gen(int(sys.argv[1])))
